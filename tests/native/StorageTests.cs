using System;
using System.Collections.Generic;
using System.IO;
using System.Reflection;
using System.Text;
using System.Threading;

// Synthetic metadata/files only. Does not execute Windows tools or encode games.
public static class StorageTests {
    static int checks;
    static void Check(bool value,string label){checks++;if(!value)throw new Exception(label);}
    static void Reject(Action action,string label){
        checks++;try{action();}catch(InvalidDataException){return;}
        catch(TargetInvocationException e){if(e.InnerException is InvalidDataException)return;throw;}
        throw new Exception("Accepted "+label);
    }
    static void U32(byte[] b,int at,uint value){Buffer.BlockCopy(BitConverter.GetBytes(value),0,b,at,4);}
    static void U64(byte[] b,int at,ulong value){Buffer.BlockCopy(BitConverter.GetBytes(value),0,b,at,8);}
    static void Be32(byte[] b,int at,uint value){for(int i=3;i>=0;i--){b[at+i]=(byte)value;value>>=8;}}
    static void Be64(byte[] b,int at,ulong value){for(int i=7;i>=0;i--){b[at+i]=(byte)value;value>>=8;}}
    static void MakeExtraction(string root,string cia) {
        byte[] exh=new byte[0x800];U64(exh,0x200,CiaSupport.TitleId);
        U32(exh,16,0x100000);U32(exh,20,0x625);U32(exh,24,0x624000);
        U32(exh,48,0x839000);U32(exh,52,1);U32(exh,56,0x800);
        byte[] code=new byte[0x626000];
        int[] offsets={0xc5328,0xc465c,0xc4f3c,0x483d4,0x55fe58,0xebd34,0xc4274,0xc3e78,0xc4214,0x448e80,0x112e4};
        uint[] words={0xe92d4038,0xe92d4010,0xe92d4010,0xe92d4fff,0xe1d010b0,0xe1a002a7,0xe594000c,0xe12fff32,0xe5943034,0xeb00335e,0xef000028};
        for(int i=0;i<offsets.Length;i++)U32(code,offsets[i],words[i]);
        byte[] exefs=new byte[1024];Buffer.BlockCopy(Encoding.ASCII.GetBytes(".code"),0,exefs,0,5);U32(exefs,12,16);
        byte[] romfs=new byte[512];Buffer.BlockCopy(Encoding.ASCII.GetBytes("IVFC"),0,romfs,0,4);
        U32(romfs,4,0x10000);U32(romfs,8,32);U32(romfs,0x54,0x5c);
        for(int i=0;i<3;i++){U64(romfs,0x14+i*24,32);U32(romfs,0x1c+i*24,5);}
        byte[] game=new byte[4096];Buffer.BlockCopy(Encoding.ASCII.GetBytes("NCCH"),0,game,0x100,4);
        U32(game,0x104,8);U64(game,0x118,CiaSupport.TitleId);U32(game,0x180,0x400);
        U32(game,0x1a0,5);U32(game,0x1a4,2);U32(game,0x1b0,7);U32(game,0x1b4,1);
        Buffer.BlockCopy(exh,0,game,512,exh.Length);Buffer.BlockCopy(exefs,0,game,0xa00,exefs.Length);Buffer.BlockCopy(romfs,0,game,0xe00,romfs.Length);
        byte[] tmd=new byte[0x140+0x9c4+0x30];Be32(tmd,0,0x00010004);Be64(tmd,0x140+0x4c,CiaSupport.TitleId);
        tmd[0x140+0x9d]=37;tmd[0x140+0x9f]=1;Be32(tmd,0x140+0x9c4,6);Be64(tmd,0x140+0x9c4+8,4096);
        byte[] image=new byte[0x2040+tmd.Length];U32(image,0,0x2020);U32(image,16,(uint)tmd.Length);Buffer.BlockCopy(tmd,0,image,0x2040,tmd.Length);
        File.WriteAllBytes(cia,image);File.WriteAllBytes(Path.Combine(root,"source.tmd"),tmd);
        File.WriteAllBytes(Path.Combine(root,"decrypted-content.0000.00000006.cxi"),game);
        File.WriteAllBytes(Path.Combine(root,"exheader.bin"),exh);File.WriteAllBytes(Path.Combine(root,"exefs.bin"),exefs);File.WriteAllBytes(Path.Combine(root,"romfs.bin"),romfs);
        Directory.CreateDirectory(Path.Combine(root,"exefs"));File.WriteAllBytes(Path.Combine(root,"exefs","code.bin"),code);
        Directory.CreateDirectory(Path.Combine(root,"romfs"));File.WriteAllBytes(Path.Combine(root,"romfs","item.bin"),new byte[]{1,2,3});
    }
    public static int Main() {
        string root=Path.Combine(Path.GetTempPath(),"dqxi-storage-tests-"+Guid.NewGuid().ToString("N"));Directory.CreateDirectory(root);
        try {
            MethodInfo snapshot=typeof(RomBuilder).GetMethod("SnapshotTree",BindingFlags.Static|BindingFlags.NonPublic);
            MethodInfo verify=typeof(RomBuilder).GetMethod("VerifyTreeSnapshot",BindingFlags.Static|BindingFlags.NonPublic);
            string expected=Path.Combine(root,"expected"),actual=Path.Combine(root,"actual");Directory.CreateDirectory(expected);Directory.CreateDirectory(actual);
            File.WriteAllText(Path.Combine(expected,"file.bin"),"same generated bytes");File.WriteAllBytes(Path.Combine(expected,"empty"),new byte[0]);
            var proof=(Dictionary<string,string>)snapshot.Invoke(null,new object[]{expected,CancellationToken.None});
            foreach(string file in Directory.GetFiles(expected))File.Copy(file,Path.Combine(actual,Path.GetFileName(file)));
            verify.Invoke(null,new object[]{proof,actual,CancellationToken.None});Check(proof.Count==2,"complete snapshot including empty files");
            File.WriteAllText(Path.Combine(actual,"file.bin"),"changed");Reject(delegate{verify.Invoke(null,new object[]{proof,actual,CancellationToken.None});},"changed decoded bytes");
            File.Copy(Path.Combine(expected,"file.bin"),Path.Combine(actual,"file.bin"),true);
            File.Move(Path.Combine(actual,"file.bin"),Path.Combine(actual,"FILE.bin"));Reject(delegate{verify.Invoke(null,new object[]{proof,actual,CancellationToken.None});},"changed file-name casing");
            File.Move(Path.Combine(actual,"FILE.bin"),Path.Combine(actual,"file.bin"));
            File.WriteAllText(Path.Combine(actual,"extra"),"extra");Reject(delegate{verify.Invoke(null,new object[]{proof,actual,CancellationToken.None});},"additional decoded file");File.Delete(Path.Combine(actual,"extra"));
            File.Delete(Path.Combine(actual,"empty"));Reject(delegate{verify.Invoke(null,new object[]{proof,actual,CancellationToken.None});},"missing decoded file");
            string prepared=Path.Combine(root,"prepared"),cia=Path.Combine(root,"original.cia");Directory.CreateDirectory(prepared);MakeExtraction(prepared,cia);
            string hash=BuildSupport.HashFile(cia);var source=CiaSupport.ReuseExtracted(cia,prepared,CancellationToken.None);
            Check(source.GamePath.EndsWith("decrypted-content.0000.00000006.cxi"),"reuse decoded content after encrypted copy released");
            Check(source.RomFsFileCount==1 && source.RomFsTotalBytes==3 && source.TitleVersion==37,"reuse complete original metadata and tree counts");
            Check(BuildSupport.HashFile(cia)==hash,"user CIA remains unchanged");
            string cached=Path.Combine(prepared,"source.tmd");byte[] tmd=File.ReadAllBytes(cached);tmd[10]^=1;File.WriteAllBytes(cached,tmd);
            Reject(delegate{CiaSupport.ReuseExtracted(cia,prepared,CancellationToken.None);},"stale cached TMD");tmd[10]^=1;File.WriteAllBytes(cached,tmd);
            File.Delete(source.GamePath);bool missing=false;
            try{CiaSupport.ReuseExtracted(cia,prepared,CancellationToken.None);}catch(FileNotFoundException){missing=true;}
            Check(missing,"released NCCH reported as recoverable missing image");
            Console.WriteLine("Native storage checks PASS: "+checks);return 0;
        } catch(Exception e){Console.Error.WriteLine(e);return 1;}
        finally{Directory.Delete(root,true);}
    }
}
